// No dependencies: retain classic-script order and existing CSS relative URLs.
// Run after editing any homepage source; --check fails on stale release files.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const groups = {
  'home.bundle.js': ['config.js', 'evidence-data.js', 'analytics.js', 'account.js', 'contribution-images.js', 'postcards.js', 'comments.js', 'script.js', 'ai-guide.js'],
  'home.bundle.css': ['style.css', 'postcards.css', 'comments.css']
};
const check = process.argv.includes('--check');
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
for (const [output, inputs] of Object.entries(groups)) {
  const separator = output.endsWith('.js') ? '\n;\n' : '\n';
  const body = '/* Generated by scripts/build-home-assets.cjs; edit source files. */\n' +
    inputs.map(file => `/* Source: ${file} */\n${fs.readFileSync(path.join(root, file), 'utf8')}`).join(separator);
  const hash = crypto.createHash('sha256').update(body).digest('hex').slice(0, 12);
  html = html.replace(new RegExp(`${output.replaceAll('.', '\\.')}\\?v=[^"\\s]+`, 'g'), `${output}?v=${hash}`);
  const target = path.join(root, output);
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== body) throw new Error(`Rebuild stale ${output}`);
  } else fs.writeFileSync(target, body);
}
const target = path.join(root, 'index.html');
if (check) {
  if (html !== fs.readFileSync(target, 'utf8')) throw new Error('Rebuild index.html asset versions');
  console.log('PASS: homepage release assets match source files.');
} else fs.writeFileSync(target, html);
